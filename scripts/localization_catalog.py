#!/usr/bin/env python3
"""Validate and compile the built-in UI catalogue. No network dependency."""
from pathlib import Path
import argparse,json,re,sys
from ui_string_inventory import inventory
ROOT=Path(__file__).resolve().parent.parent
LANGUAGES=('ru','uk','es','it','fr','pl','zh-CN')
PRINTF=re.compile(r'%(?:\d+\$)?[-+#0 ]*\d*(?:\.\d+)?(?:hh|ll|[hljztL])?[diuoxXfFeEgGaAcspn%]')
def load():
 def unique(pairs):
  result={}
  for k,v in pairs:
   if k in result:raise ValueError('Duplicate localization key: '+k)
   result[k]=v
  return result
 return json.loads((ROOT/'localization/strings.json').read_text(encoding='utf-8'),object_pairs_hook=unique)
def retained(key):
 terms=json.loads((ROOT/'localization/retained_terms.json').read_text(encoding='utf-8'))
 return key in terms or bool(re.fullmatch(r'(?:sdmc:|https?://|/|romfs:).*',key,re.S)) or bool(re.fullmatch(r'[\w./]+\.(?:log|json|txt):?\s*',key))
def generate(data):
 rows=['// Generated by scripts/localization_catalog.py; edit localization/strings.json.','static constexpr TranslationEntry kCatalog[] = {']
 for key,values in sorted(data.items()):
  quote=lambda value:json.dumps(value,ensure_ascii=False)
  rows.append('    {'+quote(key)+', {'+', '.join(quote(values[l]) for l in LANGUAGES)+'}},')
 rows+=['};','']
 return '\n'.join(rows)
def validate(data):
 errors=[]
 approved=json.loads((ROOT/'localization/retained_translations.json').read_text(encoding='utf-8'))
 for key,values in data.items():
  if set(values)!=set(LANGUAGES):errors.append(f'{key!r}: missing/unknown locales {set(LANGUAGES)^set(values)}')
  for language,text in values.items():
   if not isinstance(text,str) or not text.strip():errors.append(f'{language}: empty {key!r}');continue
   if sorted(re.findall(r'\{\d+\}',key))!=sorted(re.findall(r'\{\d+\}',text)):errors.append(f'{language}: substitution mismatch {key!r}')
   if PRINTF.findall(key)!=PRINTF.findall(text):errors.append(f'{language}: printf mismatch {key!r}')
   if key.count('\n')!=text.count('\n'):errors.append(f'{language}: newline mismatch {key!r}')
   if key==text and key not in approved.get(language,[]):errors.append(f'{language}: untranslated English value {key!r}')
   if re.search(r'ZXQ\d+QXZ|ZXPNEWLINEPXZ|\[\[K\d+',text):errors.append(f'{language}: translation artefact {key!r}')
 # All statically referenced UI labels, including settings descriptions, button
 # hints, dialogs and overlay canvas text, must be covered or a technical term.
 for key,locations in inventory(ROOT).items():
  if key not in data and not retained(key):errors.append(f'Uncatalogued UI text: {key!r} at {locations[0]}')
 return errors
if __name__=='__main__':
 parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
 try:
  data=load();errors=validate(data)
  if errors:
   print('\n'.join(errors));sys.exit(1)
  target=ROOT/'app/src/localization_catalog.inc';content=generate(data)
  if args.check:
   if not target.exists() or target.read_text(encoding='utf-8')!=content:raise ValueError('Generated localization_catalog.inc is out of date')
  else:target.write_text(content,encoding='utf-8')
  print(f'Localization: {len(data)} keys x {len(LANGUAGES)} translations; UI inventory, placeholders, printf, newlines and generated catalogue verified.')
 except (ValueError,KeyError) as error:
  print(error);sys.exit(1)
